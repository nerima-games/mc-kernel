const titleCaseId = (id: string): string =>
  id.split('_').map((word) => word[0]!.toUpperCase() + word.slice(1)).join(' ')

const englishNameFromId = (id: DisplayNameId): string =>
  ENGLISH_NAME_OVERRIDES[id] ?? titleCaseId(id)

const japaneseNameFromId = (id: DisplayNameId): string => {
  const override = JAPANESE_NAME_OVERRIDES[id]
  if (override !== undefined) return override

  // Translate the English ID-derived words; phrase overrides handle changed word order.
  return englishNameFromId(id)
    .toLowerCase()
    .replaceAll('-', ' ')
    .split(' ')
    .map((token, index, tokens) => {
      const translated = JAPANESE_TOKEN_NAMES[token as JapaneseToken]
      return index === 0 && tokens.length === 1 ? translated.replace(/の$/, '') : translated
    })
    .join('')
}

export const englishDisplayNameForId = (id: DisplayNameId): DisplayName =>
  brandDisplayName(englishNameFromId(id))

export const japaneseDisplayNameForId = (id: DisplayNameId): DisplayName =>
  brandDisplayName(japaneseNameFromId(id))

export const displayNamesForId = (id: DisplayNameId): DisplayNames => ({
  en: englishDisplayNameForId(id),
  ja: japaneseDisplayNameForId(id),
})
