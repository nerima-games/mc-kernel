const titleCaseId = (id: DisplayNameId): string =>
  id.split('_').map((word) => `${word.charAt(0).toUpperCase()}${word.slice(1)}`).join(' ')

const englishNameFromId = (id: DisplayNameId): string => ENGLISH_NAME_OVERRIDES[id] ?? titleCaseId(id)

export const englishDisplayNameForId = (id: DisplayNameId): DisplayName =>
  brandDisplayName(englishNameFromId(id))

export const japaneseDisplayNameForId = (id: DisplayNameId): DisplayName =>
  brandDisplayName(JAPANESE_NAME_TRANSLATIONS[id].name)

export const japaneseNameMethodForId = (id: DisplayNameId): JapaneseNamingMethod =>
  JAPANESE_NAME_TRANSLATIONS[id].method

export const displayNamesForId = (id: DisplayNameId): DisplayNames => ({
  en: englishDisplayNameForId(id),
  ja: japaneseDisplayNameForId(id),
})
